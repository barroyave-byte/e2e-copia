import * as xml from 'fast-xml-parser';
import { faker } from '@faker-js/faker';
import { randomUUID } from 'crypto';
import { sleep } from '@tests/order_builder/order_functions';
import { ServiceFactory, SERVICE_KEYS } from '@support/http';
import { SabreSoapResult } from '@support/http/models/sabre';

const xmlParser = new xml.XMLParser({
  ignoreAttributes: false,
  attributeNamePrefix: '@_',
});

/**
 * Creates a new Sabre merchant by generating random credentials and invoking
 * the Sabre middleware API.
 *
 * The function runs three operations in sequence as defined by the original
 * Postman `create-merchant` folder: CreateMerchant → UpdateMerchant → GetMerchant.
 *
 * @returns {Promise<SabreCredentials>} The generated merchant credentials.
 */
export const createSabreMerchant = async (
  merchantId: string,
  privateKey: string,
  merchantToken: string
): Promise<SabreCredentials> => {
  const credentials: SabreCredentials = {
    merchantAccountCode: randomUUID(),
    username: randomUUID(),
    password: faker.internet.password(),
  };

  const sabreService = ServiceFactory.getService(SERVICE_KEYS.SABRE);

  const createResponse = await sabreService.createMerchant(merchantToken, {
    deuna_merchant_id: merchantId,
    deuna_private_api_key: privateKey,
    sabre_merchant_account_code: credentials.merchantAccountCode,
    sabre_username: credentials.username,
    sabre_password: credentials.password,
    sabre_secret_key: faker.string.uuid(),
    configuration: {
      apm_url: faker.internet.url(),
      statement_descriptor: faker.company.name(),
      notification: { merchant_return_data: faker.internet.username() },
      payment_methods: {
        default_code: 'ZZ666',
        code_configuration: {
          ZZ666: {
            middleware_method: 'apm_online',
            successful_response: 'redirection_required',
            successful_description: faker.finance.accountName(),
          },
        },
      },
    },
  });

  const sabreMerchantId = createResponse.data.id;

  await sabreService.updateMerchant(merchantToken, sabreMerchantId, {
    sabre_username: credentials.username,
    sabre_password: credentials.password,
    configuration: {
      apm_url: 'http://apm.deuna.io',
      statement_descriptor: 'auto-merchant',
      notification: { merchant_return_data: 'TEST' },
      payment_methods: {
        default_code: 'AA069',
        code_configuration: {
          AA069: {
            middleware_method: 'apm_online',
            successful_response: 'redirection_required',
            successful_description: 'Redirection Required',
          },
          BB420: {
            middleware_method: 'apm_offline',
            successful_response: 'pending_payment',
            successful_description: 'Pending payment',
          },
        },
      },
    },
  });

  const getMerchantResponse = await sabreService.getMerchant(merchantToken, sabreMerchantId);
  if (!(getMerchantResponse.data as any).id) {
    throw new Error('[ERROR] ----> Sabre merchant ID is not found after creation');
  }

  console.log('[INFO] ----> Sabre Merchant Credentials: ', credentials);
  return credentials;
};

export const getAuthorizeResult = (soapResult: SabreSoapResult) => {
  let result: any = {};

  if (!soapResult.requestXml) {
    throw new Error('[ERROR] ----> Authorization Request is not found');
  }

  if (!soapResult.responseXml) {
    throw new Error('[ERROR] ----> Authorization Response is not found');
  }

  const parsedRequest = xmlParser.parse(soapResult.requestXml);
  const request = parsedRequest['soap:Envelope']['soap:Body']['AuthRQ'];
  if (!request) {
    throw new Error('[ERROR] ----> Authorize Request is empty');
  }
  result.request = request;

  const orderNumber = request['OrderDetail']['@_OrderNumber'];
  if (!orderNumber) {
    throw new Error('[ERROR] ----> Authorize Request value `OrderNumber` is empty');
  }
  result.orderNumber = orderNumber;

  const recordLocator = request['OrderDetail']['@_RecordLocator'];
  if (!recordLocator) {
    throw new Error('[ERROR] ----> Authorize Request value `RecordLocator` is empty');
  }
  result.recordLocator = recordLocator;

  // Order Id is a concatenation of PNR + Sabre Order Number. Since this could be a long string,
  // the Sabre middleware truncates it to 20 characters to avoid issues with PSPs.
  result.orderId = `${recordLocator}_${orderNumber}`.substring(0, 20);

  const parsedResponse = xmlParser.parse(soapResult.responseXml);
  const response = parsedResponse['env:Envelope']['env:Body']['AuthRS'];
  if (!response) {
    throw new Error('[ERROR] ----> Authorize Response is empty');
  }
  result.response = response;

  // This transaction ID is generated by the Sabre middleware and is not the same as the one in
  // the order, so we need to add it to the result manually to be able to use it in the posterior
  // capture or cancellation tests.
  const transactionId = response['@_TransactionID'];
  if (!transactionId) {
    throw new Error('[ERROR] ----> Authorize Response value `TransactionID` is empty');
  }
  result.transactionId = transactionId;

  console.log('[INFO] ----> Authorize Result: ', result);
  return result;
};

